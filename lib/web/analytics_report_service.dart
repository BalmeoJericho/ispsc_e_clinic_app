import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'activity_log_service.dart';

Future<void> generateAnalyticsReport({
  required int totalPatients,
  required int totalVisits,
  required int male,
  required int female,
  required Map<int, int> monthly,
  required List topLabs,
  required Map<String, int> categoryCounts,
}) async {
  final pdf = pw.Document();
  final logo = await imageFromAssetBundle('assets/school_logo.png');

////////////////////////////////////////////////////////////
/// PDF PAGE
////////////////////////////////////////////////////////////

  pdf.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,

////////////////////////////////////////////////////////////
/// HEADER
////////////////////////////////////////////////////////////

      header: (context) {
        return pw.Column(
          children: [
            pw.Row(
              children: [
                pw.Image(logo, width: 55),
                pw.SizedBox(width: 15),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      "ILOCOS SUR POLYTECHNIC STATE COLLEGE",
                      style: pw.TextStyle(
                        fontSize: 16,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.Text("Tagudin Campus Clinic"),
                    pw.Text(
                      "Clinic Analytics Report",
                      style: pw.TextStyle(
                        fontSize: 12,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
              ],
            ),
            pw.SizedBox(height: 10),
            pw.Divider(),
          ],
        );
      },

////////////////////////////////////////////////////////////
/// FOOTER
////////////////////////////////////////////////////////////

      footer: (context) {
        return pw.Column(
          children: [
            pw.SizedBox(height: 10),
            pw.Center(
              child: pw.Column(
                children: [
                  pw.Text(
                    "MRS. MARIA RONA S. GARCIA, RN",
                    style: pw.TextStyle(
                      fontWeight: pw.FontWeight.bold,
                      fontSize: 11,
                    ),
                  ),
                  pw.Text("Campus Nurse"),
                ],
              ),
            ),
            pw.SizedBox(height: 8),
            pw.Divider(),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  "Generated by ISPSC E-Clinic System",
                  style: pw.TextStyle(fontSize: 9),
                ),
                pw.Text(
                  "Page ${context.pageNumber} of ${context.pagesCount}",
                  style: pw.TextStyle(fontSize: 9),
                ),
              ],
            ),
          ],
        );
      },

////////////////////////////////////////////////////////////
/// BODY
////////////////////////////////////////////////////////////

      build: (context) => [
////////////////////////////////////////////////////////////
/// SUMMARY
////////////////////////////////////////////////////////////

        pw.Text(
          "Summary",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Text("Total Patients: $totalPatients"),
        pw.Text("Total Visits: $totalVisits"),

        pw.SizedBox(height: 20),

////////////////////////////////////////////////////////////
/// GENDER DISTRIBUTION
////////////////////////////////////////////////////////////

        pw.Text(
          "Gender Distribution",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Table(
          border: pw.TableBorder.all(),
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),
              children: [
                _headerCell("Gender"),
                _headerCell("Total"),
              ],
            ),
            pw.TableRow(
              children: [
                _cell("Male"),
                _cell(male.toString()),
              ],
            ),
            pw.TableRow(
              children: [
                _cell("Female"),
                _cell(female.toString()),
              ],
            ),
          ],
        ),

        pw.SizedBox(height: 25),

////////////////////////////////////////////////////////////
/// MONTHLY VISITS
////////////////////////////////////////////////////////////

        pw.Text(
          "Visits Per Month",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Table(
          border: pw.TableBorder.all(),
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),
              children: [
                _headerCell("Jan"),
                _headerCell("Feb"),
                _headerCell("Mar"),
                _headerCell("Apr"),
                _headerCell("May"),
                _headerCell("Jun"),
                _headerCell("Jul"),
                _headerCell("Aug"),
                _headerCell("Sep"),
                _headerCell("Oct"),
                _headerCell("Nov"),
                _headerCell("Dec"),
              ],
            ),
            pw.TableRow(
              children: List.generate(
                12,
                (index) => _cell((monthly[index + 1] ?? 0).toString()),
              ),
            ),
          ],
        ),

        pw.SizedBox(height: 25),

////////////////////////////////////////////////////////////
/// TOP LAB TESTS
////////////////////////////////////////////////////////////

        pw.Text(
          "Top 5 Laboratory Tests",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Table(
          border: pw.TableBorder.all(),
          columnWidths: {
            0: const pw.FixedColumnWidth(40),
            1: const pw.FlexColumnWidth(),
            2: const pw.FixedColumnWidth(80),
          },
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),
              children: [
                _headerCell("Rank"),
                _headerCell("Laboratory Test"),
                _headerCell("Requests"),
              ],
            ),
            ...List.generate(topLabs.length, (index) {
              final lab = topLabs[index];

              return pw.TableRow(
                children: [
                  _cell((index + 1).toString()),
                  _cell(lab.key),
                  _cell(lab.value.toString()),
                ],
              );
            }),
          ],
        ),

        pw.SizedBox(height: 25),

////////////////////////////////////////////////////////////
/// CATEGORY DISTRIBUTION
////////////////////////////////////////////////////////////

        pw.Text(
          "Laboratory Category Distribution",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Table(
          border: pw.TableBorder.all(),
          columnWidths: {
            0: const pw.FlexColumnWidth(),
            1: const pw.FixedColumnWidth(100),
          },
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),
              children: [
                _headerCell("Category"),
                _headerCell("Total Requests"),
              ],
            ),
            ...categoryCounts.entries.map((entry) {
              return pw.TableRow(
                children: [
                  _cell(entry.key),
                  _cell(entry.value.toString()),
                ],
              );
            }),
          ],
        ),
      ],
    ),
  );

////////////////////////////////////////////////////////////
/// EXPORT PDF
////////////////////////////////////////////////////////////

  final Uint8List bytes = await pdf.save();

  await Printing.layoutPdf(
    onLayout: (format) async => bytes,
  );

////////////////////////////////////////////////////////////
/// ACTIVITY LOG
////////////////////////////////////////////////////////////

  await WebActivityLogService.log(
    action: "Downloaded Analytics Report",
    details: "Clinic analytics report exported",
  );
}

////////////////////////////////////////////////////////////
/// HELPERS
////////////////////////////////////////////////////////////

pw.Widget _headerCell(String text) {
  return pw.Padding(
    padding: const pw.EdgeInsets.all(6),
    child: pw.Text(
      text,
      style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
    ),
  );
}

pw.Widget _cell(String text) {
  return pw.Padding(
    padding: const pw.EdgeInsets.all(6),
    child: pw.Text(text),
  );
}