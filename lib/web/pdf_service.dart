
import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'activity_log_service.dart';

Future<void> generatePatientPdf({
  required Map<String, dynamic> patient,
  required List visits,
}) async {

  final pdf = pw.Document();

  final logo = await imageFromAssetBundle('assets/school_logo.png');

//////////////////////////////////////////////////////
// SAFETY DATA
//////////////////////////////////////////////////////

  final patientName = patient['patientName'] ?? "";

//////////////////////////////////////////////////////
// PDF PAGE
//////////////////////////////////////////////////////

  pdf.addPage(
    pw.MultiPage(

      pageFormat: PdfPageFormat.a4,

//////////////////////////////////////////////////////
// HEADER
//////////////////////////////////////////////////////

      header: (context) {

        return pw.Column(
          children: [

            pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.center,
              children: [

                pw.Image(logo, width: 55),

                pw.SizedBox(width: 15),

                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [

                    pw.Text(
                      "ILOCOS SUR POLYTECHNIC STATE COLLEGE",
                      style: pw.TextStyle(
                        fontSize: 16,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),

                    pw.Text("Tagudin Campus Clinic"),

                    pw.Text(
                      "Patient Laboratory Test Report",
                      style: pw.TextStyle(
                        fontSize: 12,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
              ],
            ),

            pw.SizedBox(height: 10),
            pw.Divider(),
          ],
        );
      },

//////////////////////////////////////////////////////
// FOOTER
//////////////////////////////////////////////////////

      footer: (context) {

        return pw.Column(
          children: [

            pw.SizedBox(height: 10),

            pw.Center(
              child: pw.Column(
                children: [

                  pw.Text(
                    "MRS. MARIA RONA S. GARCIA, RN",
                    style: pw.TextStyle(
                      fontWeight: pw.FontWeight.bold,
                      fontSize: 11,
                    ),
                  ),

                  pw.Text(
                    "Campus Nurse",
                    style: pw.TextStyle(fontSize: 10),
                  ),
                ],
              ),
            ),

            pw.SizedBox(height: 8),

            pw.Divider(),

            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [

                pw.Text(
                  "Generated by ISPSC E-Clinic System",
                  style: pw.TextStyle(fontSize: 9),
                ),

                pw.Text(
                  "Page ${context.pageNumber} of ${context.pagesCount}",
                  style: pw.TextStyle(fontSize: 9),
                ),
              ],
            ),
          ],
        );
      },

//////////////////////////////////////////////////////
// BODY
//////////////////////////////////////////////////////

      build: (context) => [

        pw.SizedBox(height: 10),

//////////////////////////////////////////////////////
// PATIENT INFORMATION
//////////////////////////////////////////////////////

        pw.Text(
          "Patient Information",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 8),

        pw.Table(
          columnWidths: {
            0: const pw.FixedColumnWidth(120),
            1: const pw.FlexColumnWidth(),
          },
          children: [

            _row("Name", patientName),
            _row("Age", patient['age']?.toString() ?? ""),
            _row("Gender", patient['gender'] ?? ""),
            _row("Address", patient['address'] ?? ""),
          ],
        ),

        pw.SizedBox(height: 20),

//////////////////////////////////////////////////////
// VISIT HISTORY TABLE
//////////////////////////////////////////////////////

        pw.Text(
          "Visit History",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Table(
          border: pw.TableBorder.all(color: PdfColors.grey300),

          columnWidths: {
            0: const pw.FixedColumnWidth(90),
            1: const pw.FlexColumnWidth(),
            2: const pw.FlexColumnWidth(),
          },

          children: [

//////////////////////////////////////////////////////
// TABLE HEADER
//////////////////////////////////////////////////////

            pw.TableRow(
              decoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),
              children: [

                _cellHeader("Date"),
                _cellHeader("Reason"),
                _cellHeader("Laboratory Tests"),
              ],
            ),

//////////////////////////////////////////////////////
// VISIT DATA
//////////////////////////////////////////////////////

            ...visits.map((visit) {

              final tests = [

                ...List<String>.from(visit['hematology'] ?? []),
                ...List<String>.from(visit['clinicalMicroscopy'] ?? []),
                ...List<String>.from(visit['bloodChemistry'] ?? []),
                ...List<String>.from(visit['immunology'] ?? []),
                ...List<String>.from(visit['radiology'] ?? []),
                ...List<String>.from(visit['others'] ?? []),
              ];

              return pw.TableRow(
                children: [

                  _cell(visit['dateOfVisit'] ?? ""),
                  _cell(visit['reasonForVisit'] ?? ""),
                  _cell(tests.isEmpty ? "None" : tests.join(", ")),
                ],
              );

            }),
          ],
        ),
      ],
    ),
  );

//////////////////////////////////////////////////////
// GENERATE FILE
//////////////////////////////////////////////////////

  final Uint8List bytes = await pdf.save();

  await Printing.layoutPdf(
    onLayout: (format) async => bytes,
  );

//////////////////////////////////////////////////////
// ACTIVITY LOG
//////////////////////////////////////////////////////

  await WebActivityLogService.log(
    action: "Downloaded Patient Record",
    details: "Patient record exported as PDF",
    patientName: patientName,
  );
}

//////////////////////////////////////////////////////
// TABLE ROW HELPER
//////////////////////////////////////////////////////

pw.TableRow _row(String label, String value) {

  return pw.TableRow(
    children: [

      pw.Padding(
        padding: const pw.EdgeInsets.all(5),
        child: pw.Text(
          label,
          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
        ),
      ),

      pw.Padding(
        padding: const pw.EdgeInsets.all(5),
        child: pw.Text(value),
      ),
    ],
  );
}

//////////////////////////////////////////////////////
// TABLE CELL
//////////////////////////////////////////////////////

pw.Widget _cell(String text) {

  return pw.Padding(
    padding: const pw.EdgeInsets.all(6),
    child: pw.Text(text),
  );
}

pw.Widget _cellHeader(String text) {

  return pw.Padding(
    padding: const pw.EdgeInsets.all(6),
    child: pw.Text(
      text,
      style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
    ),
  );
}

