
import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'activity_log_service.dart';

Future<void> generateLogbookReport({
  required List<Map<String, dynamic>> visits,
  required String title,
}) async {

  final pdf = pw.Document();
  final logo = await imageFromAssetBundle('assets/school_logo.png');

//////////////////////////////////////////////////////
// PDF PAGE
//////////////////////////////////////////////////////

  pdf.addPage(
    pw.MultiPage(

      pageFormat: PdfPageFormat.a4,

//////////////////////////////////////////////////////
// HEADER
//////////////////////////////////////////////////////

      header: (context) {

        return pw.Column(
          children: [

            pw.Row(
              children: [

                pw.Image(logo, width: 55),

                pw.SizedBox(width: 15),

                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [

                    pw.Text(
                      "ILOCOS SUR POLYTECHNIC STATE COLLEGE",
                      style: pw.TextStyle(
                        fontSize: 16,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),

                    pw.Text("Tagudin Campus Clinic"),

                    pw.Text(
                      title,
                      style: pw.TextStyle(
                        fontSize: 12,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
              ],
            ),

            pw.SizedBox(height: 10),
            pw.Divider(),
          ],
        );
      },

//////////////////////////////////////////////////////
// FOOTER
//////////////////////////////////////////////////////

      footer: (context) {

        return pw.Column(
          children: [

            pw.SizedBox(height: 10),

            pw.Center(
              child: pw.Column(
                children: [

                  pw.Text(
                    "MRS. MARIA RONA S. GARCIA, RN",
                    style: pw.TextStyle(
                      fontWeight: pw.FontWeight.bold,
                      fontSize: 11,
                    ),
                  ),

                  pw.Text(
                    "Campus Nurse",
                    style: pw.TextStyle(fontSize: 10),
                  ),
                ],
              ),
            ),

            pw.SizedBox(height: 8),

            pw.Divider(),

            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [

                pw.Text(
                  "Generated by ISPSC E-Clinic System",
                  style: pw.TextStyle(fontSize: 9),
                ),

                pw.Text(
                  "Page ${context.pageNumber} of ${context.pagesCount}",
                  style: pw.TextStyle(fontSize: 9),
                ),
              ],
            ),
          ],
        );
      },

//////////////////////////////////////////////////////
// BODY
//////////////////////////////////////////////////////

      build: (context) => [

        pw.SizedBox(height: 10),

        pw.Text(
          "Clinic Logbook",
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

//////////////////////////////////////////////////////
// LOGBOOK TABLE
//////////////////////////////////////////////////////

        pw.Table(
          border: pw.TableBorder.all(color: PdfColors.grey300),

          columnWidths: {
            0: const pw.FixedColumnWidth(70),
            1: const pw.FixedColumnWidth(110),
            2: const pw.FixedColumnWidth(35),
            3: const pw.FixedColumnWidth(60),
            4: const pw.FlexColumnWidth(),
            5: const pw.FlexColumnWidth(),
            6: const pw.FlexColumnWidth(),
          },

          children: [

//////////////////////////////////////////////////////
// TABLE HEADER
//////////////////////////////////////////////////////

            pw.TableRow(
              decoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),

              children: [

                _header("Date"),
                _header("Name"),
                _header("Age"),
                _header("Gender"),
                _header("Address"),
                _header("Reason"),
                _header("Laboratory Tests"),
              ],
            ),

//////////////////////////////////////////////////////
// TABLE ROWS
//////////////////////////////////////////////////////

            ...visits.map((visit) {

              final tests = <String>[

                ...List<String>.from(visit['hematology'] ?? []),
                ...List<String>.from(visit['clinicalMicroscopy'] ?? []),
                ...List<String>.from(visit['bloodChemistry'] ?? []),
                ...List<String>.from(visit['immunology'] ?? []),
                ...List<String>.from(visit['radiology'] ?? []),
                ...List<String>.from(visit['others'] ?? []),
              ];

              return pw.TableRow(
                children: [

                  _cell(visit['dateOfVisit']?.toString() ?? ""),
                  _cell(visit['patientName']?.toString() ?? ""),
                  _cell(visit['age']?.toString() ?? ""),
                  _cell(visit['gender']?.toString() ?? ""),
                  _cell(visit['address']?.toString() ?? ""),
                  _cell(visit['reasonForVisit']?.toString() ?? ""),
                  _cell(tests.isEmpty ? "None" : tests.join(", ")),
                ],
              );
            }),
          ],
        ),
      ],
    ),
  );

//////////////////////////////////////////////////////
// EXPORT PDF
//////////////////////////////////////////////////////

  final Uint8List bytes = await pdf.save();

  await Printing.layoutPdf(
    onLayout: (format) async => bytes,
  );

//////////////////////////////////////////////////////
// ACTIVITY LOG
//////////////////////////////////////////////////////

  await WebActivityLogService.log(
    action: "Downloaded Logbook Report",
    details: title,
  );
}

//////////////////////////////////////////////////////
// TABLE HELPERS
//////////////////////////////////////////////////////

pw.Widget _header(String text) {

  return pw.Padding(
    padding: const pw.EdgeInsets.all(5),
    child: pw.Text(
      text,
      style: pw.TextStyle(
        fontWeight: pw.FontWeight.bold,
        fontSize: 10,
      ),
    ),
  );
}

pw.Widget _cell(String text) {

  return pw.Padding(
    padding: const pw.EdgeInsets.all(5),
    child: pw.Text(
      text,
      style: const pw.TextStyle(fontSize: 9),
    ),
  );
}

